import type { CategoryDef, TemplateDef } from "./templates";

const P = "margin:0 0 8px;line-height:1.55;font-size:13px;";
const H = "font-family:'Fraunces',serif;text-align:center;font-size:17px;font-weight:700;margin:0 0 4px;text-transform:uppercase;";

/** Хедър с фирмени данни (авто) + обект/период/отговорник (ръчно попълване). */
function haccpHead(): string {
  return `
    <p style="${P}"><strong>{{Фирма.Име}}</strong>, ЕИК {{Фирма.ЕИК}}${""}</p>
    <p style="${P}color:#444;">Обект: <span class="cda-fill" style="background:#FCEFC7;">[наименование и адрес на обекта]</span> · Месец/година: <span class="cda-fill" style="background:#FCEFC7;">[месец / {{ТекущаГодина}}]</span></p>
    <p style="${P}color:#444;">Отговорник: <span class="cda-fill" style="background:#FCEFC7;">[име и длъжност]</span> · Документ № {{Документ.Номер}}</p>`;
}

/** Ред за подписи в края на журнала. */
function haccpSign(): string {
  return `<table style="width:100%;margin-top:26px;border-collapse:collapse;"><tr>
    <td style="width:50%;padding-top:6px;border-top:1px solid #16201C;font-size:12px;">Съставил (отговорник): ....................</td>
    <td style="width:6%;"></td>
    <td style="width:44%;padding-top:6px;border-top:1px solid #16201C;font-size:12px;">Проверил (управител): .................... ({{Фирма.Управител}})</td>
  </tr></table>`;
}

/** Печатна таблица-журнал с готови колони и празни редове за записи. */
function journal(opts: { title: string; subtitle?: string; columns: { label: string; w?: string }[]; rows?: number; legend?: string; note?: string }): string {
  const rows = opts.rows ?? 16;
  const th = opts.columns
    .map((c) => `<th style="border:1px solid #16201C;padding:5px 6px;font-size:11px;background:#F3EFE4;${c.w ? `width:${c.w};` : ""}">${c.label}</th>`)
    .join("");
  const tds = opts.columns.map(() => `<td style="border:1px solid #C9C7B6;height:24px;"></td>`).join("");
  const body = Array.from({ length: rows }).map(() => `<tr>${tds}</tr>`).join("");
  return `
    <h1 style="${H}">${opts.title}</h1>
    ${opts.subtitle ? `<p style="text-align:center;color:#555;font-size:12px;margin:0 0 12px;">${opts.subtitle}</p>` : `<div style="margin-bottom:12px;"></div>`}
    ${haccpHead()}
    <table style="width:100%;border-collapse:collapse;margin-top:8px;table-layout:fixed;">
      <thead><tr><th style="border:1px solid #16201C;padding:5px 6px;font-size:11px;background:#F3EFE4;width:34px;">№</th>${th}</tr></thead>
      <tbody>${Array.from({ length: rows }).map((_, i) => `<tr><td style="border:1px solid #C9C7B6;text-align:center;font-size:11px;height:24px;">${i + 1}</td>${tds}</tr>`).join("")}</tbody>
    </table>
    ${opts.legend ? `<p style="${P}margin-top:10px;color:#444;font-size:11.5px;">${opts.legend}</p>` : ""}
    ${opts.note ? `<p style="${P}color:#444;font-size:11.5px;">${opts.note}</p>` : ""}
    ${haccpSign()}`;
}

